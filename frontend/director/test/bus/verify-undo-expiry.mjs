import assert from 'node:assert/strict';
import { fixture, result } from './fixture.mjs';
import { HISTORY_LIMIT } from '../../src/history.js';
const f = fixture();
f.register('shot.create', () => { f.edit(f.state.value + 1); return result(); });
const first = await f.bus.run('shot.create', {}, f.request('ui'));
for (let i = 0; i <= HISTORY_LIMIT; i++) await f.bus.run('shot.create', {}, f.request('ui'));
assert.equal(f.history.past.length, HISTORY_LIMIT);
const before = f.state.value;
const expired = await f.bus.run('edit.undo', { receiptId: first.receiptId }, f.request('ui'));
assert.equal(expired.code, 'UNDO_EXPIRED', JSON.stringify(expired));
assert.equal(f.state.value, before);
const last = await f.bus.run('shot.create', {}, f.request());
const restored = await f.bus.run('edit.undo', { receiptId: last.receiptId }, f.request());
assert.equal(restored.status, 'undone', JSON.stringify(restored));
assert.equal(f.state.value, before);
assert.equal(restored.undoneReceiptId, last.receiptId);
assert.equal(f.journal.get(restored.commandId), restored);
console.log('PASS bus acceptance 6: bounded history eviction refuses expired receipts and retained Undo restores');
