import assert from 'node:assert/strict';
import { fixture, deferred, result } from './fixture.mjs';
import { validateReceipt } from '../../src/studio-agent-protocol.js';
const f = fixture(), entered = deferred();
let expire, signal, delay;
f.ports.setTimeout = (fn, ms) => { expire = fn; delay = ms; return 1; };
f.ports.clearTimeout = () => {};
f.register('ai.prepareShot', (_args, context) => { signal = context.signal; entered.resolve(); return new Promise(() => {}); }, { timeoutMs: 17 });
const running = f.bus.run('ai.prepareShot', {}, f.request());
await entered.promise;
assert.equal(delay, 17);
assert.equal(signal.aborted, false);
expire();
const timeout = await running;
assert.equal(timeout.ok, false);
assert.equal(timeout.code, 'TIMEOUT');
assert.equal(signal.aborted, true);
validateReceipt(timeout);
assert.equal(f.journal.get(timeout.commandId).code, 'TIMEOUT');
const g = fixture();
g.register('ai.prepareShot', async () => ({ ...result([]), output: { count: 2 } }));
const done = await g.bus.run('ai.prepareShot', {}, g.request());
assert.equal(done.status, 'completed');
assert.deepEqual(done.output, { count: 2 });
assert.deepEqual(done.revision, { before: 0, after: 0 });
assert.equal(done.undo, null);
assert.throws(() => g.register('export.shotVideo', () => result([]), { timeoutMs: 300001 }), /timeout/);
console.log('PASS bus acceptance 3: enforced deadline aborts the job, strict TIMEOUT receipt and completed output');
