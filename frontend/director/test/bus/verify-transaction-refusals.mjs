import assert from 'node:assert/strict';
import { fixture, result, deferred } from './fixture.mjs';
const f = fixture();
f.ports.beginAction = () => { const before = f.state.value; return { run: fn => fn(), commit: () => ({ historyEntryId: 'tx-history' }), cancel: () => f.edit(before) }; };
f.register('shot.reorder', args => { f.edit(args.startFrame); f.toast('fixture-warning', 'fixture-ui'); return result(); });
const run = (id, args) => f.bus.run(id, args, f.request());
const tx = await run('run.begin', { id: 'shot.reorder', args: { shotId: 'target', startFrame: 0 } });
const updated = await run('run.update', { txId: tx.txId, args: { shotId: 'target', startFrame: 8 } });
assert.deepEqual(updated.warnings, [{ code: 'STUDIO_TOAST', message: 'fixture-warning' }]);
assert.deepEqual((await run('run.commit', { txId: tx.txId })).warnings, updated.warnings);
const entered = deferred(), release = deferred();
f.register('asset.import', async (_args, context) => { entered.resolve(); await release.promise; context.check(); f.edit(100, 'objects'); return result(); });
const args = { source: 'data:image/png;base64,AAAA', name: 'file.png', placeAs: 'cutout' };
const pending = await run('run.begin', { id: 'asset.import', args });
const update = run('run.update', { txId: pending.txId, args });
await entered.promise;
assert.equal((await run('run.commit', { txId: pending.txId })).code, 'TARGET_BUSY');
await run('run.cancel', { txId: pending.txId });
release.resolve();
assert.equal((await update).code, 'CANCELLED');
assert.equal(f.state.value, 8);
f.bus.dispose();
console.log('PASS bus wire updates: accumulated warnings, no premature commit and cancelled late publication');
