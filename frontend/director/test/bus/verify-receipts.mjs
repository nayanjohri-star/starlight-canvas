import assert from 'node:assert/strict';
import { fixture, result, host } from './fixture.mjs';
import { validateReceipt } from '../../src/studio-agent-protocol.js';
const f = fixture();
f.register('shot.remove', () => { f.edit(f.state.value + 1); return result(['shot-1']); });
const receipt = await f.bus.run('shot.remove', { shotId: 'shot-1' }, f.request('ui'));
assert.equal(receipt.ok, true);
assert.equal(receipt.status, 'applied');
assert.equal(typeof receipt.undo.historyEntryId, 'string');
assert.deepEqual(receipt.revision, { before: 0, after: 1 });
assert.deepEqual(validateReceipt(receipt), receipt);
assert.equal(f.history.past.length, 1);
assert.equal(f.journal.get(receipt.commandId), receipt);
const request = f.request();
const first = await f.bus.run('shot.remove', { shotId: 'shot-1' }, request);
assert.deepEqual(await f.bus.run('shot.remove', { shotId: 'shot-1' }, request), first);
assert.equal(f.state.revision, 2, 'a retry must not run again, even with a now-stale revision');
assert.equal((await f.bus.run('shot.remove', { shotId: 'different' }, request)).code, 'INVALID_ARGUMENT');
assert.equal((await f.bus.run('shot.remove', {}, f.request())).code, 'INVALID_ARGUMENT');
assert.equal((await f.bus.run('shot.remove', { shotId: 'shot-1' }, f.request('agent', { expectedRevision: 0 }))).code, 'STALE_SCENE');
assert.equal((await f.bus.run('shot.remove', { shotId: 'shot-1' }, f.request('cli', { host: { ...host, sceneEpoch: 'old' } }))).code, 'STALE_SCENE');
f.patch({ busy: true });
assert.equal((await f.bus.run('shot.remove', { shotId: 'shot-1' }, f.request('mcp'))).code, 'TARGET_BUSY');
f.register('shot.create', () => { throw new Error('must not run'); }, { available: () => 'Not ready in this fixture.' });
assert.equal((await f.bus.run('shot.create', {}, f.request('ui'))).message, 'Not ready in this fixture.');
console.log('PASS bus acceptance 1: UI receipts, strict validation, admission and journal idempotency');
